  /** Blight each hand brings back from a trip. */
  blight: number;
  /** Flasks of lamp oil each hand burns on the way down and back. */
  oil: number;
  /** Leagues of delve the company counts once this floor is first taken (the story's measure of depth). */
  leagues: number;
  /** Chance a returning assault party brings back a fragment of the Key. */
  fragment: number;
